// Generates design/sistema/tokens.css from design/tokens.json (DTCG format).
// Usage: node scripts/build-tokens.mjs [--check]
// --check exits with code 1 when the committed CSS is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const SRC = `${root}design/tokens.json`;
const OUT = `${root}design/sistema/tokens.css`;

const tokens = JSON.parse(readFileSync(SRC, 'utf8'));

/** Group path → CSS custom property prefix. */
const PREFIX = {
  space: 'sp-',
  radius: 'r-',
  size: 'sz-',
  layout: '',
  'motion.duration': 'dur-',
  'motion.easing': 'ease-',
  'motion.cycle': 'cycle-',
  'font.family': 'font-',
  'font.stretch': '',
  'font.weight': 'fw-',
  'font.leading': 'lh-',
};

const isToken = (node) => node && typeof node === 'object' && '$value' in node;

/** Yields [name, token] for the direct and nested tokens of a group. */
function* entries(group) {
  for (const [key, node] of Object.entries(group)) {
    if (key.startsWith('$')) continue;
    if (isToken(node)) yield [key, node];
  }
}

/** Resolves a DTCG alias such as {space.4} to the CSS variable it generates. */
function alias(value) {
  return value.replace(/\{([a-z]+)\.([a-z0-9-]+)\}/g, (_m, group, key) => {
    const prefix = PREFIX[group];
    if (prefix === undefined) throw new Error(`Unknown alias group: ${group}`);
    return `var(--${prefix}${key})`;
  });
}

function cssValue(token) {
  const v = token.$value;
  if (Array.isArray(v)) {
    if (token.$type === 'cubicBezier' || v.every((n) => typeof n === 'number')) {
      return `cubic-bezier(${v.join(', ')})`;
    }
    return v.map((f) => (/\s/.test(f) ? `'${f}'` : f)).join(', ');
  }
  return typeof v === 'string' ? alias(v) : String(v);
}

function declarations(group, prefix, indent = '  ') {
  return [...entries(group)].map(([k, t]) => `${indent}--${prefix}${k}: ${cssValue(t)};`);
}

const out = [];
out.push('/* Generated by scripts/build-tokens.mjs from design/tokens.json. Do not edit. */');
out.push('');
out.push(':root {');
for (const [path, prefix] of Object.entries(PREFIX)) {
  const group = path.split('.').reduce((node, key) => node[key], tokens);
  out.push(...declarations(group, prefix));
}
out.push('}');

for (const theme of ['dark', 'light']) {
  const sel =
    theme === 'dark' ? ":root,\n:root[data-theme='dark']" : `:root[data-theme='${theme}']`;
  out.push('');
  out.push(`${sel} {`);
  out.push(...declarations(tokens.color[theme], ''));
  out.push(...declarations(tokens.shadow[theme], 'shadow-'));
  out.push(`  color-scheme: ${theme};`);
  out.push('}');
}

for (const density of ['compact', 'comfortable']) {
  const sel =
    density === 'compact'
      ? ":root,\n:root[data-density='compact']"
      : `:root[data-density='${density}']`;
  out.push('');
  out.push(`${sel} {`);
  out.push(...declarations(tokens.density[density], ''));
  out.push('}');
}

out.push('');
out.push('/* Reduced motion: transitions collapse; cycles are switched off in componenti.css. */');
out.push('@media (prefers-reduced-motion: reduce) {');
out.push('  :root {');
for (const [k] of entries(tokens.motion.duration)) out.push(`    --dur-${k}: 0ms;`);
out.push('  }');
out.push('}');
out.push('');

const css = out.join('\n');

if (process.argv.includes('--check')) {
  const current = readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n');
  if (current !== css) {
    console.error('design/sistema/tokens.css is out of date: run node scripts/build-tokens.mjs');
    process.exit(1);
  }
  console.log('tokens.css is up to date');
} else {
  writeFileSync(OUT, css);
  console.log(`wrote ${OUT}`);
}
